/** The generated `sitecustomize.py` of the guard folder `dir` (its path written in).
    Before anything else imports, it sets aside every `sys.path` entry inside one of the
    `checkouts` folders but outside the `keep` folders, the guard and the interpreter's own
    prefixes, plus the meta-path finders of editable installs: an editable install
    (uv, hatchling, setuptools) otherwise puts the checkout's code back on the path. */
export const guardScript = (
	dir,
	{ checkouts = [], keep = [] } = {},
) => `# Generated by rpiv reprove-red: records what this Python process loaded.
import atexit
import importlib.util
import os
import sys
import sysconfig
import threading

try:
    import fcntl
except ImportError:
    fcntl = None

_RECORDS = os.path.join(${JSON.stringify(dir.replaceAll("\\", "/"))}, "records")
_CLAIM = os.path.join(${JSON.stringify(dir.replaceAll("\\", "/"))}, "root")
_CHECKOUTS = ${pyPaths(checkouts)}
_KEEP = ${pyPaths([dir, ...keep])}
_EDITABLE_FINDERS = ("__editable__", "_editable_impl_")
_KINDS = ("stdlib", "platstdlib", "purelib", "platlib")
_IMPORTABLE = (".py", ".pyc", ".pyd", ".so")
_WRITES = os.O_WRONLY | os.O_RDWR | os.O_APPEND | os.O_CREAT
_state = {}


def _claim():
    try:
        fd = os.open(_CLAIM, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        return "child"
    try:
        os.write(fd, str(os.getpid()).encode("ascii"))
    finally:
        os.close(fd)
    return "root"


def _high(fd):
    if hasattr(fcntl, "F_DUPFD_CLOEXEC"):
        return fcntl.fcntl(fd, fcntl.F_DUPFD_CLOEXEC, 3)
    new = fcntl.fcntl(fd, fcntl.F_DUPFD, 3)
    os.set_inheritable(new, False)
    return new


def _open_record(name):
    flags = os.O_CREAT | os.O_EXCL | os.O_WRONLY | getattr(os, "O_BINARY", 0)
    fd = os.open(name, flags)
    if fd < 3 and fcntl is not None:
        low = fd
        try:
            fd = _high(low)
        finally:
            os.close(low)
    return os.fdopen(fd, "w", encoding="utf-8")


def _start(role=None):
    pid = os.getpid()
    role = role or _claim()
    name = os.path.join(_RECORDS, "%d-%s.txt" % (pid, os.urandom(8).hex()))
    handle = _open_record(name)
    handle.write("start: " + str(pid) + "\\n")
    handle.write("role: " + role + "\\n")
    handle.write("ppid: " + str(os.getppid()) + "\\n")
    handle.flush()
    _state["lock"] = threading.RLock()
    _state["handle"] = handle
    _state["pid"] = pid


def _write(line):
    with _state["lock"]:
        handle = _state.get("handle")
        if handle is not None and _state.get("pid") == os.getpid():
            handle.write(line + "\\n")
            handle.flush()


def _reads(mode, flags):
    if isinstance(mode, str):
        return not any(ch in mode for ch in "wax+")
    return not (isinstance(flags, int) and flags & _WRITES)


def _audit(event, args):
    if event != "open":
        return
    try:
        path = args[0]
        if isinstance(path, bytes):
            path = os.fsdecode(path)
        if not isinstance(path, str) or not path.lower().endswith(_IMPORTABLE):
            return
        if not _reads(args[1], args[2] if len(args) > 2 else None):
            return
        if path.lower().endswith(".pyc"):
            try:
                path = importlib.util.source_from_cache(path)
            except Exception:
                pass
        _write("module: " + os.path.realpath(path))
    except Exception:
        pass


def _lines():
    paths = sysconfig.get_paths()
    for kind in _KINDS:
        if paths.get(kind):
            yield "package: " + os.path.realpath(paths[kind])
    for module in list(sys.modules.values()):
        try:
            path = module.__file__
            if isinstance(path, str) and path:
                yield "module: " + os.path.realpath(path)
        except Exception:
            continue


def _finish():
    if _state.get("handle") is None or _state.get("pid") != os.getpid():
        return
    with _state["lock"]:
        handle = _state["handle"]
        try:
            for line in _lines():
                handle.write(line + "\\n")
            handle.write("end: " + str(os.getpid()) + "\\n")
        finally:
            _state["handle"] = None
            handle.close()


def _child():
    _state.pop("handle", None)
    _start("child")


def _norm(path):
    return os.path.normcase(os.path.realpath(path))


def _inside(folder, path):
    try:
        return os.path.commonpath([folder, path]) == folder
    except ValueError:
        return False


def _set_aside():
    checkouts = [_norm(p) for p in _CHECKOUTS]
    keep = [_norm(p) for p in _KEEP + [sys.prefix, sys.base_prefix]]

    def leaks(entry):
        if not isinstance(entry, str):
            return False
        path = _norm(entry or os.getcwd())
        if not any(_inside(c, path) for c in checkouts):
            return False
        return not any(_inside(k, path) for k in keep)

    sys.path[:] = [entry for entry in sys.path if not leaks(entry)]
    sys.meta_path[:] = [
        finder
        for finder in sys.meta_path
        if not str(getattr(finder, "__module__", "")).startswith(_EDITABLE_FINDERS)
    ]


try:
    _set_aside()
except Exception:
    pass
_start()
sys.addaudithook(_audit)
atexit.register(_finish)
if hasattr(os, "register_at_fork"):
    os.register_at_fork(after_in_child=_child)
`;
