/** A path's real path, symlinks and junctions resolved, without a `\\?\` prefix. A path
    that does not exist keeps its missing tail on its nearest real ancestor. */
export const realOf = (path) => {
	const full = resolve(path);
	try {
		return realpathSync.native(full).replace(/^\\\\\?\\/, "");
	} catch {
		const parent = dirname(full);
		return parent === full ? full : join(realOf(parent), basename(full));
	}
};

/** True when `path` is `folder` or lies inside it (Windows: any case, any slash). A
    folder whose name starts with `..` (`..cache`) is inside; only `..` itself leads out. */
export const within = (folder, path) => {
	const rel = relative(folder, path);
	const leavesFolder = rel === ".." || rel.startsWith(`..${sep}`);
	return !leavesFolder && !isAbsolute(rel);
};

/** git's stdout as text, run in `cwd`; a failure throws one line naming git and its
    first stderr line (the shape of reprove-red's own git calls). */
const gitOut = (cwd, args) => {
	try {
		return execFileSync("git", args, {
			cwd,
			encoding: "utf-8",
			stdio: ["ignore", "pipe", "pipe"],
		});
	} catch (error) {
		const why = String(error.stderr || error.message)
			.trim()
			.split("\n")[0];
		throw new Error(`git ${args[0]} failed: ${why}`);
	}
};

/** The real top folders of every worktree of the repository at `top`, as git lists them. */
export const checkoutFolders = (top) =>
	gitOut(top, ["worktree", "list", "--porcelain"])
		.split(/\r?\n/)
		.filter((line) => line.startsWith("worktree "))
		.map((line) => realOf(line.slice("worktree ".length)));

/** A list of paths as a Python list literal, `/` inside each path. */
const pyPaths = (paths) =>
	JSON.stringify(paths.map((path) => path.replaceAll("\\", "/")));

