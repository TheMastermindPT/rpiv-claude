/** The generated `sitecustomize.py` of the guard folder `dir` (its path written in). */
export const guardScript = (
	dir,
) => `# Generated by rpiv reprove-red: records what this Python process loaded.
import atexit
import importlib.util
import os
import sys
import sysconfig
import threading

_RECORDS = os.path.join(${JSON.stringify(dir.replaceAll("\\", "/"))}, "records")
_KINDS = ("stdlib", "platstdlib", "purelib", "platlib")
_IMPORTABLE = (".py", ".pyc", ".pyd", ".so")
_WRITES = os.O_WRONLY | os.O_RDWR | os.O_APPEND | os.O_CREAT
_state = {}


def _start():
    pid = os.getpid()
    name = os.path.join(_RECORDS, "%d-%s.txt" % (pid, os.urandom(8).hex()))
    handle = open(name, "x", encoding="utf-8")
    handle.write("start: " + str(pid) + "\\n")
    handle.flush()
    _state["lock"] = threading.RLock()
    _state["handle"] = handle
    _state["pid"] = pid


def _write(line):
    with _state["lock"]:
        handle = _state.get("handle")
        if handle is not None and _state.get("pid") == os.getpid():
            handle.write(line + "\\n")
            handle.flush()


def _reads(mode, flags):
    if isinstance(mode, str):
        return not any(ch in mode for ch in "wax+")
    return not (isinstance(flags, int) and flags & _WRITES)


def _audit(event, args):
    if event != "open":
        return
    try:
        path = args[0]
        if isinstance(path, bytes):
            path = os.fsdecode(path)
        if not isinstance(path, str) or not path.lower().endswith(_IMPORTABLE):
            return
        if not _reads(args[1], args[2] if len(args) > 2 else None):
            return
        if path.lower().endswith(".pyc"):
            try:
                path = importlib.util.source_from_cache(path)
            except Exception:
                pass
        _write("module: " + os.path.realpath(path))
    except Exception:
        pass


def _lines():
    paths = sysconfig.get_paths()
    for kind in _KINDS:
        if paths.get(kind):
            yield "package: " + os.path.realpath(paths[kind])
    for module in list(sys.modules.values()):
        try:
            path = module.__file__
            if isinstance(path, str) and path:
                yield "module: " + os.path.realpath(path)
        except Exception:
            continue


def _finish():
    if _state.get("handle") is None or _state.get("pid") != os.getpid():
        return
    with _state["lock"]:
        handle = _state["handle"]
        try:
            for line in _lines():
                handle.write(line + "\\n")
            handle.write("end: " + str(os.getpid()) + "\\n")
        finally:
            _state["handle"] = None
            handle.close()


def _child():
    _state.pop("handle", None)
    _start()


_start()
sys.addaudithook(_audit)
atexit.register(_finish)
if hasattr(os, "register_at_fork"):
    os.register_at_fork(after_in_child=_child)
`;
