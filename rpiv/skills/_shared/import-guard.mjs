// import-guard.mjs — the venv guard of a Python re-run (D11, D12, D18, D20 of the
// Python-support design, S2-scratch-copy). reprove-red makes a fresh guard folder
// outside every checkout folder, holding a generated `sitecustomize.py` and a `records/`
// folder, and puts it first on the runner's PYTHONPATH. Every Python process that loads
// the guard writes its own record file: `start: <pid>`, then at exit a `package:` line
// for each of Python's standard library and site-packages folders, a `module:` line for
// the file of each loaded module, and `end: <pid>`. An audit hook also writes a
// `module:` line at once for each importable file the process opens for reading (a cached
// `.pyc` as its source), so a module dropped from `sys.modules` before exit is still seen
// (D21, S2b-guard-proof). The system's temporary folder is checked before the guard
// folder is made (D23), and an unfinished record reads
// `result: broken: import record incomplete: pid <n>` (D24).
//
// Importable-only: no CLI, no isMain.
// Importable: guardScript, createGuard, guardEnv, checkoutFolders, readRecords,
// importVerdict, realOf, within.

import { execFileSync } from "node:child_process";
import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	realpathSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import {
	basename,
	delimiter,
	dirname,
	isAbsolute,
	join,
	relative,
	resolve,
	sep,
} from "node:path";

/** A path's real path, symlinks and junctions resolved, without a `\\?\` prefix. A path
    that does not exist keeps its missing tail on its nearest real ancestor. */
export const realOf = (path) => {
	const full = resolve(path);
	try {
		return realpathSync.native(full).replace(/^\\\\\?\\/, "");
	} catch {
		const parent = dirname(full);
		return parent === full ? full : join(realOf(parent), basename(full));
	}
};

/** True when `path` is `folder` or lies inside it (Windows: any case, any slash). A
    folder whose name starts with `..` (`..cache`) is inside; only `..` itself leads out. */
export const within = (folder, path) => {
	const rel = relative(folder, path);
	const leavesFolder = rel === ".." || rel.startsWith(`..${sep}`);
	return !leavesFolder && !isAbsolute(rel);
};

/** git's stdout as text, run in `cwd`; a failure throws one line naming git and its
    first stderr line (the shape of reprove-red's own git calls). */
const gitOut = (cwd, args) => {
	try {
		return execFileSync("git", args, {
			cwd,
			encoding: "utf-8",
			stdio: ["ignore", "pipe", "pipe"],
		});
	} catch (error) {
		const why = String(error.stderr || error.message)
			.trim()
			.split("\n")[0];
		throw new Error(`git ${args[0]} failed: ${why}`);
	}
};

/** The real top folders of every worktree of the repository at `top`, as git lists them. */
export const checkoutFolders = (top) =>
	gitOut(top, ["worktree", "list", "--porcelain"])
		.split(/\r?\n/)
		.filter((line) => line.startsWith("worktree "))
		.map((line) => realOf(line.slice("worktree ".length)));

